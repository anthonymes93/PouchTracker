test('unknown sleep coverage excludes ordinary XP, historical confirmation restores evidence and deletion makes it provisional',async({page})=>{
 await page.addInitScript(()=>{
  localStorage.setItem('fixture-entries',JSON.stringify([{id:'start',uid:'test-user',kind:'pouch',time:Date.parse('2026-10-25T13:00Z'),costCents:100},{id:'end',uid:'test-user',kind:'pouch',time:Date.parse('2026-10-25T16:00Z'),costCents:100}]))
  localStorage.setItem('fixture-coverage',JSON.stringify([{date:'2026-10-25',complete:true}]))
 })
 await page.goto('/settings/sleep');await page.getByRole('button',{name:'Confirm awake period',exact:true}).click()
 await page.getByLabel('Start date and time').fill('2026-10-25T09:00');await page.getByLabel('End date and time').fill('2026-10-25T12:00')
 await page.getByRole('button',{name:'Save period',exact:true}).click()
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('fixture-rewards')||'[]').filter((a:{status:string})=>a.status==='valid').length)).toBeGreaterThan(0)
 await page.getByRole('button',{name:/^Delete awake /}).click();await page.getByRole('button',{name:'Delete period',exact:true}).click()
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('fixture-rewards')||'[]').filter((a:{type:string;status:string})=>a.type==='spacing'&&a.status==='valid').length)).toBe(0)
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('fixture-rewards')||'[]').some((a:{status:string})=>a.status==='provisional'))).toBe(true)
})
