 await page.goto('/settings/sleep')
 await page.getByRole('button',{name:'Add sleep period',exact:true}).click()
 await page.getByLabel('Start date and time').fill('2026-10-25T12:00');await page.getByLabel('End date and time').fill('2026-10-25T14:00')
