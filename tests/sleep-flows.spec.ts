import { expect,test } from '@playwright/test'
import { isolateFirebase } from './fixtures/browser'
test.beforeEach(async({page})=>{
 await isolateFirebase(page);await page.clock.setFixedTime(new Date('2026-10-26T18:00Z'))
 await page.addInitScript(()=>{if(!localStorage.getItem('sleep-seeded')){localStorage.setItem('sleep-seeded','yes');localStorage.setItem('fixture-sleep',JSON.stringify({schemaVersion:2,revision:1,periods:[],interruption:null}))}})
})
test.afterEach(async({page})=>expect((await page.pageErrors()).map(error=>error.message)).toEqual([]))
for(const theme of ['forest','ocean'])test(`irregular sleep, pouch interruption and explicit return in ${theme}`,async({page},info)=>{
 await page.addInitScript(theme=>localStorage.setItem('fixture-preferences',JSON.stringify({theme})),theme)
 await page.setViewportSize({width:320,height:568});await page.goto('/')
 await expect(page.getByRole('button',{name:'Log Pouch',exact:true})).toBeInViewport({ratio:1})
 await page.locator('.sleep-controls summary').click()
 await page.getByRole('button',{name:"I'm Going to Sleep",exact:true}).click()
 await expect(page.getByRole('button',{name:"I'm Awake",exact:true})).toBeVisible()
 await page.clock.setFixedTime(new Date('2026-10-26T19:00Z'))
 await page.getByRole('button',{name:'Log Pouch',exact:true}).click()
 await expect(page.getByText(/Did you return to sleep/)).toBeVisible()
 const data=await page.evaluate(()=>({sleep:JSON.parse(localStorage.getItem('fixture-sleep')!),entries:JSON.parse(localStorage.getItem('fixture-entries')!)}))
 expect(data.sleep.periods[0].endMs).toBe(data.entries[0].time)
 expect(data.sleep.periods.filter((p:{endMs:number|null})=>p.endMs===null)).toHaveLength(0)
 await page.getByRole('button',{name:"I'm Going Back to Sleep Now"}).click()
 await page.clock.setFixedTime(new Date('2026-10-26T20:00Z'))
 await page.getByRole('button',{name:"I'm Awake",exact:true}).click()
 await expect(page.getByRole('timer')).toHaveAttribute('aria-label','01 hours, 00 minutes, 00 seconds')
 await page.goto('/settings/sleep')
 await expect(page.locator('.sleep-row')).toHaveCount(2)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('sleep-tracking-320.png')})
 await page.reload();await expect(page.locator('.sleep-row')).toHaveCount(2)
})
