import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { isolateFirebase } from './fixtures/browser'
const NOW = new Date('2026-10-24T16:00:00Z')
const count = (page: Page, label: string) => page.locator('.stat-card').filter({ hasText: label }).locator('.stat-value')
const stored = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fixture-entries') || '[]') as { id: string; kind: string; time: number; costCents: number | null }[])
test.beforeEach(async ({ page }) => { await isolateFirebase(page); await page.clock.install({ time: new Date(NOW.getTime() - 1000) }); await page.clock.pauseAt(NOW) })
test.afterEach(async ({ page }) => { expect((await page.pageErrors()).map(error => error.message)).toEqual([]) })

test('one-tap logging, double-tap suppression, cigarette timer independence, and Undo', async ({ page }) => {
  await page.goto('/')
  const pouch = page.getByRole('button', { name: 'Log Pouch', exact: true })
  await pouch.evaluate(button => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click() })
  await expect(count(page, 'Pouches today')).toHaveText('1')
  expect((await stored(page)).length).toBe(1)
  await expect(page.getByRole('timer')).toHaveAttribute('aria-label', /00 hours, 00 minutes, 00 seconds/)
  await page.clock.runFor(5000)
  await page.getByRole('button', { name: 'Log Cigarette', exact: true }).click()
  await expect(count(page, 'Cigarettes today')).toHaveText('1')
  await expect(page.getByRole('timer')).toHaveAttribute('aria-label', /00 hours, 00 minutes, 05 seconds/)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(count(page, 'Cigarettes today')).toHaveText('0')
  expect((await stored(page)).map(entry => entry.kind)).toEqual(['pouch'])
})

test('cigar prices are stored per entry and last selected price is highlighted', async ({ page }) => {
  await page.goto('/')
  for (const price of ['1.90', '2.30', '2.50']) {
    await page.getByRole('button', { name: 'Log Cigar', exact: true }).click()
    await page.getByRole('button', { name: new RegExp(`\\$${price}`) }).click()
    await page.clock.runFor(2000)
  }
  await expect(count(page, 'Cigars today')).toHaveText('3')
  await expect(count(page, 'Total uses today')).toHaveText('3')
  expect((await stored(page)).map(entry => entry.costCents)).toEqual([190, 230, 250])
  await page.getByRole('button', { name: 'Log Cigar', exact: true }).click()
  await expect(page.getByRole('button', { name: '$2.50 Last selected' })).toHaveClass(/selected/)
  await expect(page.getByRole('timer')).toHaveAttribute('aria-label', 'Timer not started')
})

test('timer survives refresh and recalculates after editing and deleting newest pouch', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  await page.clock.runFor(3000)
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  await page.clock.runFor(3000)
  await page.reload()
  await expect(page.getByRole('timer')).toHaveAttribute('aria-label', /00 hours, 00 minutes, 03 seconds/)
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'History' }).click()
  await page.getByRole('button', { name: /^Edit pouch/ }).first().click()
  await page.getByLabel('Date and time').fill('2026-10-24T11:00')
  await page.getByRole('button', { name: 'Save time' }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.getByRole('timer')).toHaveAttribute('aria-label', /00 hours, 00 minutes, 06 seconds/)
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'History' }).click()
  await page.getByRole('button', { name: /^Delete pouch/ }).first().click()
  await page.getByRole('button', { name: 'Delete entry', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.getByRole('timer')).toHaveAttribute('aria-label', /01 hours, 00 minutes, 06 seconds/)
  await expect(count(page, 'Pouches today')).toHaveText('1')
})

test('today resets at Toronto midnight without resetting the pouch timer', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-25T03:59:59Z'))
  await page.goto('/')
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  await expect(count(page, 'Pouches today')).toHaveText('1')
  await page.clock.setFixedTime(new Date('2026-10-25T04:00:01Z'))
  await page.clock.runFor(1000)
  await expect(count(page, 'Pouches today')).toHaveText('0')
  await expect(page.getByRole('timer')).not.toHaveAttribute('aria-label', 'Timer not started')
})

test('theme is instant, persists on refresh, accepts another tab update, and clears on sign-out', async ({ page, context }) => {
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Ocean Blue' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'ocean')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Ocean Blue' })).toHaveAttribute('aria-pressed', 'true')
  const other = await context.newPage()
  await isolateFirebase(other)
  await other.goto('/settings')
  await expect(other.getByRole('button', { name: 'Ocean Blue' })).toHaveAttribute('aria-pressed', 'true')
  await other.getByRole('button', { name: 'Forest Green' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'forest')
  await page.getByRole('button', { name: 'Ocean Blue' }).click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'forest')
  expect(await page.evaluate(() => localStorage.getItem('pouch-tracker-theme'))).toBeNull()
  await other.close()
})

test('loading, read errors and failed writes are clear and recoverable', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('fixture-mode', 'loading'))
  await page.reload()
  await expect(page.getByText('Loading your latest pouch…')).toBeVisible()
  await page.evaluate(() => { localStorage.setItem('fixture-mode', 'error'); window.dispatchEvent(new Event('fixture-update')) })
  await expect(page.getByRole('button', { name: 'Retry timer' })).toBeVisible()
  await page.evaluate(() => localStorage.removeItem('fixture-mode'))
  await page.getByRole('button', { name: 'Retry timer' }).click()
  await expect(count(page, 'Pouches today')).toHaveText('0')
  await page.evaluate(() => localStorage.setItem('fixture-write-error', 'true'))
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Could not save test entry.' })).toBeVisible()
  await expect(count(page, 'Pouches today')).toHaveText('0')
  expect(await stored(page)).toHaveLength(0)
})

test('Undo while a create is still pending does not restore its success notification', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('fixture-delay', 'true'))
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await page.clock.runFor(4000)
  await expect(count(page, 'Pouches today')).toHaveText('0')
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toHaveCount(0)
  expect(await stored(page)).toHaveLength(0)
})

