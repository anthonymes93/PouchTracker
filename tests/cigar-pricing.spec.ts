import { expect, test } from '@playwright/test'
import { Timestamp } from 'firebase/firestore'
import { cigarPresets, cigarSnapshot, parseCigarPrice, validCigarPresets } from '../src/utils/cigarPricing'
import { EMPTY_PRICING } from '../src/types/finance'
import { formatCost } from '../src/utils/money'
import { dailyReport, spending } from '../src/utils/finance'
import type { Entry } from '../src/types/data'
import { isolateFirebase } from './fixtures/browser'

test('legacy defaults, preset validation, and exact custom individual prices', () => {
  expect(cigarPresets(EMPTY_PRICING)).toEqual([190, 230, 250])
  expect(cigarPresets({ ...EMPTY_PRICING, cigarPresetsCents: [215, 275, 325] })).toEqual([215, 275, 325])
  expect(validCigarPresets([190, 230])).toBe(false)
  expect(validCigarPresets([190, 230, -1])).toBe(false)
  expect(validCigarPresets([190, 230, 2.5])).toBe(false)
  expect(cigarSnapshot(parseCigarPrice('3.75'))).toEqual({ packCents: 375, quantity: 1 })
  for (const invalid of ['', '-1', '1.999', 'Infinity', '100000.01']) expect(() => parseCigarPrice(invalid)).toThrow()
})

test('custom cigar snapshots feed spending and versioned savings without preset repricing', () => {
  const entry: Entry = { id: 'cigar', uid: 'unit', kind: 'cigar', occurredAt: Timestamp.fromMillis(Date.parse('2026-10-23T16:00:00Z')), createdAt: null, updatedAt: null, currency: 'CAD', costCents: 375, priceSnapshot: cigarSnapshot(375), pending: false }
  expect(formatCost(spending([entry]).total)).toBe('$3.75')
  const report = dailyReport([entry], [{ id: '2026-10-23', effectiveOn: '2026-10-23', createdAt: null, categories: { cigar: { dailyCountMilli: 2000, price: cigarSnapshot(300) } } }], [{ date: '2026-10-23', complete: true, updatedAt: null }], '2026-10-23', '2026-10-23', '2026-10-24')
  expect(formatCost(report[0].savings)).toBe('$2.25')
  expect(formatCost(spending([]).total)).toBe('$0.00')
  expect(formatCost(spending([{ ...entry }]).total)).toBe('$3.75')
})

test('presets sync between sessions, remember selection, and preserve old snapshot prices', async ({ page, context }) => {
  await isolateFirebase(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Log Cigar', exact: true }).click()
  await page.getByRole('button', { name: '$1.90 CAD', exact: true }).click()
  const other = await context.newPage()
  await isolateFirebase(other)
  await other.goto('/settings')
  const section = other.getByRole('group', { name: 'Cigar Pricing', exact: true })
  await expect(section.getByLabel('Per-cigar preset 1 (CAD)')).toHaveValue('1.90')
  await expect(section.getByText(/pack|quantity/i)).toHaveCount(0)
  await section.getByLabel('Per-cigar preset 1 (CAD)').fill('2.75')
  await section.getByLabel('Per-cigar preset 2 (CAD)').fill('3.10')
  await section.getByLabel('Per-cigar preset 3 (CAD)').fill('3.50')
  await other.getByRole('button', { name: 'Save pricing', exact: true }).click()
  await expect(other.getByText('Pricing saved. Existing entries keep their recorded costs.')).toBeVisible()
  await page.getByRole('button', { name: 'Log Cigar', exact: true }).click()
  await page.getByRole('button', { name: '$2.75 CAD', exact: true }).click()
  await page.getByRole('button', { name: 'Log Cigar', exact: true }).click()
  await expect(page.getByRole('button', { name: '$2.75 Last selected' })).toHaveClass(/selected/)
  await page.getByRole('button', { name: 'Close panel' }).click()
  await page.goto('/history')
  await expect(page.getByText('$1.90 CAD', { exact: true })).toBeVisible()
  await expect(page.getByText('$2.75 CAD', { exact: true })).toBeVisible()
  const entries = await page.evaluate(() => JSON.parse(localStorage.getItem('fixture-entries') || '[]') as { priceSnapshot: { packCents: number; quantity: number } }[])
  expect(entries.map(entry => entry.priceSnapshot)).toEqual([{ packCents: 190, quantity: 1 }, { packCents: 275, quantity: 1 }])
  await other.close()
  expect(await page.pageErrors()).toEqual([])
})

