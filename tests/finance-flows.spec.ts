import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { isolateFirebase } from './fixtures/browser'
const NOW = new Date('2026-10-24T16:00:00Z')
test.beforeEach(async ({ page }) => { await isolateFirebase(page); await page.clock.setFixedTime(NOW) })
test.afterEach(async ({ page }) => expect((await page.pageErrors()).map(error => error.message)).toEqual([]))
async function pricing(page: Page, amount: string, quantity: string) {
  await page.goto('/settings')
  await page.locator('#pricing-pouch-price').fill(amount)
  await page.locator('#pricing-pouch-quantity').fill(quantity)
  await page.getByRole('button', { name: 'Save pricing', exact: true }).click()
  await expect(page.getByText('Pricing saved. Existing entries keep their recorded costs.')).toBeVisible()
}
const entries = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fixture-entries') || '[]') as { id: string; priceSnapshot?: { packCents: number; quantity: number }; time: number }[])

test('pricing snapshots survive new prices, time-only edits, deletion and Undo', async ({ page }) => {
  await pricing(page, '12.99', '20')
  await page.goto('/')
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  const original = (await entries(page))[0]
  expect(original.priceSnapshot).toEqual({ packCents: 1299, quantity: 20 })
  await pricing(page, '20.00', '20')
  await page.goto('/')
  await page.getByRole('button', { name: 'Log Pouch', exact: true }).click()
  expect((await entries(page))[0].priceSnapshot).toEqual(original.priceSnapshot)
  expect((await entries(page))[1].priceSnapshot).toEqual({ packCents: 2000, quantity: 20 })
  await expect(page.locator('.stat-card').filter({ hasText: 'Spent today' }).locator('.stat-value')).toHaveText('$1.65')
  await page.goto('/history')
  await page.getByRole('button', { name: /^Edit pouch/ }).first().click()
  await page.getByLabel('Date and time').fill('2026-10-24T11:00')
  await page.getByRole('button', { name: 'Save time' }).click()
  expect((await entries(page)).find(value => value.id === original.id)?.priceSnapshot).toEqual(original.priceSnapshot)
  await page.getByRole('button', { name: /^Delete pouch/ }).last().click()
  await page.getByRole('button', { name: 'Delete entry', exact: true }).click()
  expect(await entries(page)).toHaveLength(1)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  expect(await entries(page)).toHaveLength(2)
  expect((await entries(page)).find(value => value.id === original.id)?.priceSnapshot).toEqual(original.priceSnapshot)
})

