test('baseline requires explicit inputs and coverage; a new version preserves the earlier estimate', async ({ page }) => {
  await page.goto('/settings')
  await page.getByLabel('Effective start date').fill('2026-10-23')
  await page.getByLabel('Include Pouches', { exact: true }).check()
  await page.getByLabel('Baseline pouches per day').fill('12')
  await page.locator('#baseline-pouch-price').fill('13.00')
  await page.locator('#baseline-pouch-quantity').fill('20')
  await page.getByRole('button', { name: 'Save new baseline version' }).click()
  await expect(page.getByText('Baseline version saved. Earlier versions are preserved.')).toBeVisible()
  await page.goto('/stats')
  await expect(page.locator('.report-section').filter({ has: page.getByRole('heading', { name: 'Estimated savings', exact: true }) }).locator('.report-total')).toHaveText('Not available')
  await page.getByText('Confirm a complete tracking day', { exact: true }).click()
  await page.getByRole('button', { name: 'I recorded all use for this day' }).click()
  await expect(page.getByText('Day confirmed complete.')).toBeVisible()
  await expect(page.locator('.report-section').filter({ has: page.getByRole('heading', { name: 'Estimated savings', exact: true }) }).locator('.report-total')).toHaveText('$7.80')
  await page.goto('/settings')
  await page.getByLabel('Effective start date').fill('2026-10-25')
  await page.getByLabel('Include Pouches', { exact: true }).check()
  await page.getByLabel('Baseline pouches per day').fill('6')
  await page.locator('#baseline-pouch-price').fill('13.00')
  await page.locator('#baseline-pouch-quantity').fill('20')
  await page.getByRole('button', { name: 'Save new baseline version' }).click()
  await expect(page.locator('.baseline-history li')).toHaveCount(2)
  await page.goto('/stats')
  await expect(page.locator('.report-section').filter({ has: page.getByRole('heading', { name: 'Estimated savings', exact: true }) }).locator('.report-total')).toHaveText('$7.80')
})

test('history-derived baseline suggestion is not applied until accepted', async ({ page }) => {
  await page.goto('/settings')
  await page.evaluate(() => {
    localStorage.setItem('fixture-coverage', JSON.stringify([{ date: '2026-10-23', complete: true }]))
    localStorage.setItem('fixture-entries', JSON.stringify([{ id: 'one', uid: 'test-user', kind: 'pouch', time: Date.parse('2026-10-23T16:00:00Z'), costCents: null }]))
    window.dispatchEvent(new Event('fixture-update'))
  })
  await page.getByLabel('Include Pouches', { exact: true }).check()
  await page.getByText('Suggest daily quantities from my history', { exact: true }).click()
  await page.getByLabel('From', { exact: true }).fill('2026-10-23')
  await page.getByLabel('Through', { exact: true }).fill('2026-10-23')
  await page.getByRole('button', { name: 'Calculate suggestion' }).click()
  await expect(page.getByLabel('Baseline pouches per day')).toHaveValue('')
  await page.getByRole('button', { name: 'Accept suggested quantities' }).click()
  await expect(page.getByLabel('Baseline pouches per day')).toHaveValue('1')
  expect(await page.evaluate(() => localStorage.getItem('fixture-baselines'))).toBeNull()
})

